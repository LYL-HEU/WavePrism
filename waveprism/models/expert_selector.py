class ResidualConvBlock(nn.Module):
    def __init__(self, in_ch: int, out_ch: int, dropout: float = 0.0):
        super().__init__()

        self.proj = nn.Identity() if in_ch == out_ch else nn.Conv2d(in_ch, out_ch, kernel_size=1)

        self.net = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.GELU(),
            nn.Dropout2d(dropout),
            nn.Conv2d(out_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
        )

        self.act = nn.GELU()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.act(self.net(x) + self.proj(x))


class MultiScaleContextBlock(nn.Module):
    def __init__(self, in_ch: int, out_ch: int, dropout: float = 0.0):
        super().__init__()

        branch_ch = max(out_ch // 4, 1)

        self.b1 = nn.Sequential(nn.Conv2d(in_ch, branch_ch, kernel_size=1), nn.GELU())
        self.b2 = nn.Sequential(
            nn.Conv2d(in_ch, branch_ch, kernel_size=3, padding=1, dilation=1), nn.GELU()
        )
        self.b3 = nn.Sequential(
            nn.Conv2d(in_ch, branch_ch, kernel_size=3, padding=2, dilation=2), nn.GELU()
        )
        self.b4 = nn.Sequential(
            nn.Conv2d(in_ch, branch_ch, kernel_size=3, padding=4, dilation=4), nn.GELU()
        )

        self.fuse = nn.Sequential(
            nn.Conv2d(branch_ch * 4, out_ch, kernel_size=1), nn.GELU(), nn.Dropout2d(dropout)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.fuse(torch.cat([self.b1(x), self.b2(x), self.b3(x), self.b4(x)], dim=1))


class FrozenStage1WindEncoder(nn.Module):
    """Frozen Stage-1 encoder plus K decoders. Returns (z, generated_experts)."""

    def __init__(self, cfg):
        super().__init__()
        context = get_stage1_context()
        self.core = WaveExpertModel(**context["meta"])
        state = {
            key.removeprefix("module."): value
            for key, value in context["checkpoint"]["model"].items()
        }
        self.core.load_state_dict(state, strict=True)
        self.out_channels = int(context["meta"]["latent_channels"])
        self.encoder_amp = bool(cfg.encoder_amp)
        self.register_buffer("geometry", torch.from_numpy(context["geometry"][None].copy()))
        self.freeze()

    def freeze(self):
        self.requires_grad_(False)
        super().train(False)

    def train(self, mode=True):
        # Parent selector.train() must never enable pretrained dropout.
        self.freeze()
        return self

    def forward(self, x_in):
        if x_in.ndim != 5 or x_in.shape[1:3] != (self.core.history_hours, self.core.wind_channels):
            raise ValueError("Frozen encoder requires complete [B,history,C,H,W] wind input.")
        with (
            torch.no_grad(),
            autocast_context(x_in.device.type, self.encoder_amp and x_in.device.type == "cuda"),
        ):
            geometry = self.geometry.expand(x_in.shape[0], -1, -1, -1)
            prediction, z = self.core(x_in, geometry, return_latent=True)
        prediction = prediction.float().detach()
        ocean = self.geometry[:, -1:] > 0.5
        prediction = prediction.masked_fill(~ocean, float("nan"))
        if not torch.isfinite(prediction.masked_select(ocean.expand_as(prediction))).all():
            raise FloatingPointError("Nonfinite Stage-1 prediction over ocean.")
        return z.float().detach(), prediction


class ExpertSelector(nn.Module):
    """Select generated experts using state features and a TRAIN-only spatial skill prior."""

    def __init__(self, cfg: Stage2Config, prior=None):
        super().__init__()

        self.cfg = cfg
        self.num_experts = cfg.num_experts
        self.use_expert_features = cfg.use_expert_features

        # TRAIN-only expert skill prior
        self.use_expert_skill_prior = bool(cfg.use_expert_skill_prior)

        self.skill_prior_logits_fixed = None
        self.skill_prior_confidence_fixed = None

        if self.use_expert_skill_prior:
            if prior is None:
                with np.load(cfg.expert_skill_prior_npz) as data:
                    prior_logits_np = np.asarray(data["prior_logits"], dtype=np.float32)
                    prior_conf_np = np.asarray(data["prior_confidence"], dtype=np.float32)
            else:
                prior_logits_np, prior_conf_np = prior

            if prior_logits_np.shape[0] != cfg.num_experts:
                raise ValueError(
                    f"prior K={prior_logits_np.shape[0]} != cfg.num_experts={cfg.num_experts}"
                )

            self.skill_prior_logits_fixed = nn.Parameter(
                torch.from_numpy(prior_logits_np[None, ...]), requires_grad=False
            )

            self.skill_prior_confidence_fixed = nn.Parameter(
                torch.from_numpy(prior_conf_np[None, ...]), requires_grad=False
            )

            if cfg.skill_prior_use_logit_bias:
                if cfg.skill_prior_alpha_init <= 0:
                    raise ValueError("skill_prior_alpha_init must be > 0")

                # inverse softplus:
                # raw = log(exp(alpha)-1)
                alpha_raw_init = math.log(math.expm1(float(cfg.skill_prior_alpha_init)))

                self.skill_prior_alpha_raw = nn.Parameter(
                    torch.tensor(alpha_raw_init, dtype=torch.float32),
                    requires_grad=cfg.skill_prior_alpha_learnable,
                )
            else:
                self.skill_prior_alpha_raw = None

        # Reuse the one frozen model already used for TRAIN statistics.
        self.wind_encoder = get_stage1_context().get("backbone")
        if self.wind_encoder is None:
            self.wind_encoder = FrozenStage1WindEncoder(cfg)

        z_ch = self.wind_encoder.out_channels
        selector_in_ch = z_ch

        if cfg.use_expert_features:
            selector_in_ch += cfg.num_experts + cfg.num_experts + 4
            # A2
            if cfg.use_expert_anomaly_features:
                selector_in_ch += cfg.num_experts
            if cfg.use_expert_normalized_anomaly_features:
                selector_in_ch += cfg.num_experts

        if cfg.use_static_features:
            selector_in_ch += cfg.static_channels
        if cfg.use_position_features:
            selector_in_ch += cfg.position_channels

        # Spatial expert-skill prior as explicit input feature.
        # prior_logits: K channels
        # confidence : 1 channel
        if cfg.use_expert_skill_prior and cfg.skill_prior_use_as_feature:
            selector_in_ch += cfg.num_experts

            if cfg.skill_prior_use_confidence_feature:
                selector_in_ch += 1

        self.selector_in_channels = selector_in_ch

        self.selector = nn.Sequential(
            ResidualConvBlock(selector_in_ch, cfg.selector_hidden_channels, dropout=cfg.dropout),
            ResidualConvBlock(
                cfg.selector_hidden_channels, cfg.selector_hidden_channels, dropout=cfg.dropout
            ),
            MultiScaleContextBlock(
                cfg.selector_hidden_channels, cfg.selector_hidden_channels, dropout=cfg.dropout
            ),
            ResidualConvBlock(
                cfg.selector_hidden_channels, cfg.selector_hidden_channels, dropout=cfg.dropout
            ),
            nn.Conv2d(cfg.selector_hidden_channels, cfg.num_experts, kernel_size=1),
        )

        # final_logits = 0 + alpha * prior_logits
        if (
            cfg.use_expert_skill_prior
            and cfg.skill_prior_use_logit_bias
            and cfg.initialize_dynamic_logits_zero
        ):
            final_conv = self.selector[-1]
            if not isinstance(final_conv, nn.Conv2d):
                raise TypeError("Expected final selector layer to be Conv2d.")
            nn.init.zeros_(final_conv.weight)
            if final_conv.bias is not None:
                nn.init.zeros_(final_conv.bias)

    def get_skill_prior_alpha(self) -> torch.Tensor:
        if not self.use_expert_skill_prior or not self.cfg.skill_prior_use_logit_bias:
            return torch.tensor(0.0, device=next(self.parameters()).device)

        return F.softplus(self.skill_prior_alpha_raw)

    def get_skill_prior_maps(self, batch_size: int, h: int, w: int):
        if not self.use_expert_skill_prior:
            return None, None

        prior_logits = self.skill_prior_logits_fixed
        prior_conf = self.skill_prior_confidence_fixed

        if prior_logits.shape[-2:] != (h, w):
            raise ValueError(f"Skill-prior H/W {prior_logits.shape[-2:]} != model H/W {(h, w)}")

        if prior_conf.shape[-2:] != (h, w):
            raise ValueError(f"Skill-prior confidence H/W {prior_conf.shape[-2:]} != {(h, w)}")

        prior_logits = prior_logits.expand(batch_size, -1, -1, -1)
        prior_conf = prior_conf.expand(batch_size, -1, -1, -1)

        return prior_logits, prior_conf

    def build_expert_features(self, m_mod: torch.Tensor):
        expert_valid = torch.isfinite(m_mod).float()
        m_safe = torch.nan_to_num(m_mod, nan=0.0, posinf=0.0, neginf=0.0)

        denom = expert_valid.sum(dim=1, keepdim=True).clamp_min(1.0)
        m_mean = (m_safe * expert_valid).sum(dim=1, keepdim=True) / denom

        centered = (m_safe - m_mean) * expert_valid
        m_var = (centered**2).sum(dim=1, keepdim=True) / denom
        m_std = torch.sqrt(m_var + 1e-8)

        m_anomaly = centered
        m_anomaly_norm = (centered / (m_std + float(self.cfg.expert_anomaly_eps))) * expert_valid

        m_for_min = torch.where(expert_valid > 0.5, m_safe, torch.full_like(m_safe, float("inf")))
        m_for_max = torch.where(expert_valid > 0.5, m_safe, torch.full_like(m_safe, -float("inf")))
        m_min = torch.min(m_for_min, dim=1, keepdim=True).values
        m_max = torch.max(m_for_max, dim=1, keepdim=True).values
        m_min = torch.where(torch.isfinite(m_min), m_min, torch.zeros_like(m_min))
        m_max = torch.where(torch.isfinite(m_max), m_max, torch.zeros_like(m_max))
        m_range = m_max - m_min

        return (
            m_safe,
            expert_valid,
            m_mean,
            m_std,
            m_min,
            m_max,
            m_range,
            m_anomaly,
            m_anomaly_norm,
        )

    def forward(
        self,
        x_in: torch.Tensor,
        m_mod: torch.Tensor,
        static: Optional[torch.Tensor] = None,
        position: Optional[torch.Tensor] = None,
    ) -> Dict[str, torch.Tensor]:
        if x_in.ndim == 5:
            # Direct inference: ignore any externally supplied candidate tensor.
            z, m_mod = self.wind_encoder(x_in)
        elif x_in.ndim == 4:
            # Trainer already generated BOTH inputs in prepare_generated_batch.
            z = x_in
        else:
            raise ValueError("Expected raw history [B,T,C,H,W] or generated z [B,C,H,W].")

        (m_safe, expert_valid, m_mean, m_std, m_min, m_max, m_range, m_anomaly, m_anomaly_norm) = (
            self.build_expert_features(m_mod)
        )

        features = [z]

        if self.use_expert_features:
            features.extend([m_safe, expert_valid, m_mean, m_std, m_min, m_max])
            if self.cfg.use_expert_anomaly_features:
                features.append(m_anomaly)
            if self.cfg.use_expert_normalized_anomaly_features:
                features.append(m_anomaly_norm)

        if self.cfg.use_static_features:
            if static is None:
                raise ValueError("cfg.use_static_features=True, but static is None.")
            if static.shape[-2:] != z.shape[-2:]:
                raise ValueError(f"static H/W {static.shape[-2:]} != model H/W {z.shape[-2:]}")
            features.append(static)

        if self.cfg.use_position_features:
            if position is None:
                raise ValueError("cfg.use_position_features=True, but position is None.")
            if position.shape[1] != self.cfg.position_channels:
                raise ValueError(
                    f"position channels={position.shape[1]}, expected={self.cfg.position_channels}"
                )
            if position.shape[-2:] != z.shape[-2:]:
                raise ValueError(f"position H/W {position.shape[-2:]} != model H/W {z.shape[-2:]}")
            features.append(position)

        # TRAIN-only spatial expert-skill prior
        prior_logits = None
        prior_confidence = None

        if self.use_expert_skill_prior:
            prior_logits, prior_confidence = self.get_skill_prior_maps(
                batch_size=z.shape[0], h=z.shape[-2], w=z.shape[-1]
            )

            if self.cfg.skill_prior_use_as_feature:
                features.append(prior_logits)

                if self.cfg.skill_prior_use_confidence_feature:
                    features.append(prior_confidence)

        selector_in = torch.cat(features, dim=1)
        if selector_in.shape[1] != self.selector_in_channels:
            raise RuntimeError(
                f"selector_in channels={selector_in.shape[1]}, expected={self.selector_in_channels}"
            )

        # Dynamic residual logits learned from current sea state.
        logits_dynamic = self.selector(selector_in)

        # Explicit prior + dynamic correction:
        # final_logits =
        #     dynamic_logits + alpha * spatial_prior_logits
        # alpha > 0 and can be learnable.
        if self.use_expert_skill_prior and self.cfg.skill_prior_use_logit_bias:
            prior_alpha = self.get_skill_prior_alpha()
            logits = logits_dynamic + prior_alpha * prior_logits
        else:
            prior_alpha = torch.tensor(
                0.0, dtype=logits_dynamic.dtype, device=logits_dynamic.device
            )
            logits = logits_dynamic

        logits_masked = logits.masked_fill(expert_valid < 0.5, -1.0e4)
        prob = F.softmax(logits_masked, dim=1)

        pred_idx = torch.argmax(prob, dim=1, keepdim=True)
        selected_pred = torch.gather(m_safe, dim=1, index=pred_idx)

        selected_onehot = (
            F.one_hot(pred_idx[:, 0, :, :].long(), num_classes=self.num_experts)
            .permute(0, 3, 1, 2)
            .float()
        )
        selector_conf = prob.max(dim=1, keepdim=True).values

        return {
            "z": z,
            "m_mod": m_mod,
            "logits": logits,
            "logits_dynamic": logits_dynamic,
            "logits_masked": logits_masked,
            "prob": prob,
            "pred_idx": pred_idx,
            "skill_prior_logits": prior_logits,
            "skill_prior_confidence": prior_confidence,
            "skill_prior_alpha": prior_alpha,
            "selected_pred": selected_pred,
            "selected_onehot": selected_onehot,
            "selector_conf": selector_conf,
            "m_safe": m_safe,
            "expert_valid": expert_valid,
            "m_mean": m_mean,
            "m_std": m_std,
            "m_min": m_min,
            "m_max": m_max,
            "m_range": m_range,
            "m_anomaly": m_anomaly,
            "m_anomaly_norm": m_anomaly_norm,
        }
